export const languages = Object.keys(text);

export function translator(lang) {
  const table = text[lang] ?? text.en;
  return (key, params = {}) => {
    const template = table[key];
    if (template === undefined) throw new Error(`missing ${lang} text ${key}`);
    return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
  };
}

// describeCondition turns a WeatherKit code such as "MostlyCloudy" into words.
export function describeCondition(code, lang) {
  if (lang === "zh" && conditions[code]) return conditions[code];
  return code.replace(/([a-z])([A-Z])/g, "$1 $2").toLowerCase();
}
